// Icons and display names for the investment pages, from the aoe4world data
// repo (github.com/aoe4world/data) at the commit the metric is pinned to.
//
//   npx tsx packages/investment-web/scripts/icons.ts            (from the repo root)
//   npx tsx packages/investment-web/scripts/icons.ts --data <local clone of aoe4world/data>
//
// It copies the icon of everything the metric can count (analysis/investment/
// categories.json: units, production buildings, defenses and their upgrades,
// walls) and of every age-up (landmarks, and the technologies some civs age up
// with) into web/public/icons, and writes web/src/icons.generated.ts: for each
// of them, its icon and its name. Icons already copied are kept. Run it again
// after refresh-game-data moves the pinned commit or categories.json gains ids.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = join(HERE, '..');
const ROOT = join(PKG, '..', '..');
const ICON_DIR = join(PKG, 'web', 'public', 'icons');
const MANIFEST = join(PKG, 'web', 'src', 'icons.generated.ts');

type Kind = 'unit' | 'building' | 'technology';
const FILE: Record<Kind, string> = { unit: 'units/all-optimized.json', building: 'buildings/all-optimized.json', technology: 'technologies/all-optimized.json' };

interface Raw { id: string; name: string; icon?: string }
interface GameData { commit: string; items: Record<string, { kind: Kind; baseId: string; ageUp?: true }[]> }
interface Categories { buckets: Record<string, Partial<Record<Kind, string[]>>>; ageUpLandmarks: Record<string, string[]> }

const dataArg = (() => { const i = process.argv.indexOf('--data'); return i > 0 ? process.argv[i + 1] ?? null : null; })();

const gameData = JSON.parse(readFileSync(join(ROOT, 'analysis', 'investment', 'game-data.json'), 'utf8')) as GameData;
const categories = JSON.parse(readFileSync(join(ROOT, 'analysis', 'investment', 'categories.json'), 'utf8')) as Categories;
const RAW = `https://raw.githubusercontent.com/aoe4world/data/${gameData.commit}/`;

async function readText(path: string): Promise<string> {
  if (dataArg) return readFileSync(join(dataArg, path), 'utf8');
  const res = await fetch(RAW + path);
  if (!res.ok) throw new Error(`Could not fetch ${RAW + path}: ${res.status}`);
  return res.text();
}
async function readBytes(path: string): Promise<Uint8Array | null> {
  if (dataArg) { const p = join(dataArg, path); return existsSync(p) ? readFileSync(p) : null; }
  const res = await fetch(RAW + path);
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`Could not fetch ${RAW + path}: ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

// What needs an icon: kind:id.
const wanted = new Set<string>();
for (const bucket of Object.values(categories.buckets)) {
  for (const [kind, ids] of Object.entries(bucket) as [Kind, string[]][]) for (const id of ids) wanted.add(`${kind}:${id}`);
}
for (const ids of Object.values(categories.ageUpLandmarks)) for (const id of ids) wanted.add(`building:${id}`);
for (const list of Object.values(gameData.items)) for (const v of list) if (v.ageUp) wanted.add(`${v.kind}:${v.baseId}`);

const byKind = new Map<Kind, Map<string, Raw>>();
for (const kind of Object.keys(FILE) as Kind[]) {
  const data = (JSON.parse(await readText(FILE[kind])) as { data: Raw[] }).data;
  byKind.set(kind, new Map(data.map((x) => [x.id, x])));
}

const entries: [string, { icon: string | null; name: string }][] = [];
let copied = 0;
const missing: string[] = [];
for (const key of [...wanted].sort()) {
  const [kind, id] = key.split(':') as [Kind, string];
  const raw = byKind.get(kind)?.get(id);
  if (!raw) { missing.push(key); continue; }
  const rel = raw.icon && raw.icon.includes('/images/') ? raw.icon.split('/images/')[1]! : null;
  let icon: string | null = null;
  if (rel) {
    const dest = join(ICON_DIR, rel);
    if (existsSync(dest)) icon = rel;
    else {
      const bytes = await readBytes('images/' + rel);
      if (bytes) {
        mkdirSync(dirname(dest), { recursive: true });
        writeFileSync(dest, bytes);
        copied++;
        icon = rel;
      }
    }
  }
  if (!icon) missing.push(key + ' (no icon file)');
  entries.push([key, { icon, name: raw.name }]);
}

const lines = [
  '// Generated by scripts/icons.ts from the aoe4world data repo at commit ' + gameData.commit + '.',
  '// kind:id -> the icon under /icons/ (null when the data has none) and the name the game uses.',
  '// Do not edit by hand: run the script again.',
  'export const ITEMS: Readonly<Record<string, { icon: string | null; name: string }>> = {',
  ...entries.map(([k, v]) => `  ${JSON.stringify(k)}: { icon: ${JSON.stringify(v.icon)}, name: ${JSON.stringify(v.name)} },`),
  '};',
  '',
];
mkdirSync(dirname(MANIFEST), { recursive: true });
writeFileSync(MANIFEST, lines.join('\n'));
console.log(`${entries.length} items, ${copied} icons copied now, manifest written to ${MANIFEST}.`);
if (missing.length) console.log('Not found in the data or without an icon:\n  ' + missing.join('\n  '));
